void seq_cmd_set_octave(SeqChannel *ch)
{
    ch->octave = *ch->pos++;
}

void seq_cmd_octave_up(SeqChannel *ch)
{
    ch->octave = (ch->octave + 1) & 0xF;
}

/* The game adds 0xFFFF here, not -1: the step is an unsigned short. */
void seq_cmd_octave_down(SeqChannel *ch)
{
    ch->octave = (ch->octave + (unsigned short)-1) & 0xF;
}

